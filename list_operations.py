#list operations
cricketers=['rohit','virat','msd','surya']
print(cricketers)
#append
cricketers.append('tilak')
print(cricketers)
#insert
cricketers.insert(1,'bumrah')
print(cricketers)
#remove
cricketers.remove('bumrah')
print(cricketers)
#pop
cricketers.pop(4)
print(cricketers)
#slicing
print(cricketers[0:3])